def generate_icebreaker_text(data, templates_dict=None):
    sender_name = data.get("sender_name", "Павел")
    title = data.get("title", "клиники")
    rating = data.get("rating", "5.0")
    comp_1 = data.get("comp_1") or "конкурентам"
    comp_2 = data.get("comp_2") or "соседним клиникам"
    competitors = f"«{comp_1}» или «{comp_2}»" if data.get("comp_1") and data.get("comp_2") else f"«{comp_1}»"
    lost_leads = data.get("lost_leads", "2–4")
    lost_revenue = f"{data.get('lost_revenue', 0):,}".replace(",", " ")

    # Сценарий для лидеров (балл >= 75)
    if data.get("is_leader", False) or data.get("score", 0) >= 75:
        return (
            f"Добрый день!\n\n"
            f"Меня зовут {sender_name}, анализирую поисковую гео-выдачу Яндекса в вашем районе.\n\n"
            f"У «{title}» сформирована сильная репутация (оценка {rating}), однако в карточке "
            f"есть несколько скрытых технических точек роста, из-за которых часть первичных обращений "
            f"перехватывают ближайшие соседи ({competitors}).\n\n"
            f"По трафику локации клиника недополучает порядка {lost_leads} первичных пациентов в месяц "
            f"(около {lost_revenue} ₽ выручки).\n\n"
            f"Свели детальный аудит в короткий 4-страничный отчет. Отправить PDF руководителю? (можно просто ответить «Да» или ➕)"
        )

    # Сценарий для клиник, требующих оптимизации (балл < 75)
    return (
        f"Добрый день!\n\n"
        f"Меня зовут {sender_name}, я анализирую, как пациенты находят стоматологии на Яндекс Картах. "
        f"На этой неделе мы сравнивали, как распределяется поток записей между клиниками вашего района.\n\n"
        f"У «{title}» высокая репутация и сильная оценка ({rating}). Однако из-за отсутствия прямой "
        f"онлайн-записи и неполного описания услуг профиль клиники теряет позиции в выдаче, и часть первичных "
        f"пациентов уходит в {competitors}.\n\n"
        f"По трафику локации клиника каждый месяц упускает около {lost_leads} первичных обращений "
        f"(это порядка {lost_revenue} ₽ недополученной выручки).\n\n"
        f"Мы свели эти технические ошибки в короткий 4-страничный разбор. Скинуть сюда PDF для главврача "
        f"или управляющего? (можно просто ответить «Да» или ➕)"
    )
