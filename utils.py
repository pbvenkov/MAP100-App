import re

def generate_icebreaker_text(data: dict) -> str:
    """
    Генерирует законченное персонализированное письмо первого касания (Icebreaker)
    для мессенджеров (WhatsApp / Telegram) или Email без сокращений и оборванных фраз.
    """
    # 1. Корректное обращение без дублей и официоза
    raw_lpr = str(data.get("lpr_name", "")).strip()
    stop_words = ["добрый день", "здравствуйте", "коллеги", "администратор", "none", ""]
    
    if not raw_lpr or raw_lpr.lower() in stop_words:
        greeting = "Здравствуйте!"
    else:
        # Оставляем только имя, если пришло ФИО
        first_name = raw_lpr.split()[0]
        greeting = f"Здравствуйте, {first_name}!"

    # 2. Переменные карточки и конкурентов
    title = data.get("title", "вашей компании").strip()
    rating = data.get("rating", 4.7)
    
    comp_1 = data.get("comp_1") or data.get("competitor_1") or "соседним организациям"
    comp_2 = data.get("comp_2") or data.get("competitor_2") or "прямым конкурентам"
    
    lost_leads = data.get("lost_leads", "30–40")
    lost_revenue = data.get("lost_revenue", 0)
    
    # Форматирование суммы с разделителями тысяч
    if isinstance(lost_revenue, (int, float)):
        revenue_str = f"{lost_revenue:,}".replace(',', ' ') + " ₽"
    else:
        revenue_str = f"{lost_revenue} ₽"

    sender_name = data.get("sender_name", "Павел").strip() or "Павел"

    # 3. Полное целостное тело письма
    message = f"""{greeting}

Меня зовут {sender_name}, команда локального маркетинга PIN100.

Мы провели независимый аудит видимости карточки «{title}» в поисковой выдаче и картах Яндекса.

Ключевой факт: у компании сформирован отличный клиентский опыт и высокая оценка ({rating} на основе обратной связи). Однако с технической точки зрения витрина не оптимизирована под поисковые алгоритмы. По целевым коммерческим запросам карточка ранжируется ниже своего потенциала, перенаправляя входящий горячий спрос к вашим соседям по локации — «{comp_1}» и «{comp_2}».

Масштаб финансовых потерь: из-за неучтенных факторов ранжирования компания ежемесячно упускает порядка {lost_leads} первичных обращений. В пересчете на средний чек сегмента это создает кассовый разрыв около {revenue_str} недополученной выручки каждый месяц.

Мы собрали детальный 4-страничный аналитический отчет с оценкой по 79 параметрам Яндекса и пошаговым планом устранения уязвимостей.

Файл сформирован, рекламы внутри нет. Напишите «Да» в ответном сообщении — сразу направлю PDF для изучения."""

    return message.strip()
